#!/usr/bin/env python3
"""
DEV/theme-uses-gen.py - generate CFG/THEME-USES.BM: which theme keys each SUB /
FUNCTION reads.

Theme Edit's inspector shows a picked part's COMPUTED properties - the theme keys
it is drawn with. A part names the routine that draws it ("@SW_draw_checkbox" in
the files string it gives THEMEED_seen); this table turns that into its keys:

  THEMEU_keys$ (routine)   "KEY KEY ..." - every theme key the routine reads
                           (THEME.<field>), in the order it first reads them

Fields map to keys through THEME_apply_kv% (CFG/CONFIG-THEME.BM), the theme
loader - the same source DEV/theme-props-gen.py reads. Every .BM / .BAS in the
tree is scanned (not includes/, which never reads THEME), comments and string
literals left out. Only direct reads count: a helper's keys are the helper's.

  python3 DEV/theme-uses-gen.py           write CFG/THEME-USES.BM (only when it changed)
  python3 DEV/theme-uses-gen.py --check   exit 1 when the file is out of date

`make` runs it before every build (writing, not failing: any source edit can
change it); the file is committed so a plain qb64pe compile works too.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOADER = os.path.join(ROOT, "CFG", "CONFIG-THEME.BM")
OUT = os.path.join(ROOT, "CFG", "THEME-USES.BM")
SKIP_FILES = {"CFG/CONFIG-THEME.BM", "CFG/THEME-PROPS.BM", "CFG/THEME-USES.BM"}
SKIP_DIRS = {"includes", ".git", "QA", "DEV", "PLANS", "docs", "ASSETS", "native", "node_modules"}

CASE_RE = re.compile(r'^\s*CASE\s+"([A-Z0-9_]+)"\s*:\s*THEME\.([A-Za-z0-9_]+)')
START_RE = re.compile(r'^\s*(?:SUB|FUNCTION)\s+([A-Za-z0-9_]+)', re.I)
END_RE = re.compile(r'^\s*END\s+(?:SUB|FUNCTION)\b', re.I)
REF_RE = re.compile(r'\bTHEME\.([A-Za-z0-9_]+)', re.I)


def field_keys():
    """THEME field (upper, no suffix) -> its theme key (the loader's first CASE)."""
    out = {}
    lines = open(LOADER, encoding="utf-8").read().split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("FUNCTION THEME_apply_kv%"))
    for l in lines[start:]:
        if l.startswith("END FUNCTION"):
            break
        m = CASE_RE.match(l)
        if m:
            out.setdefault(m.group(2).upper(), m.group(1))
    return out


def code_part(line):
    """The line without its comment and string literals."""
    out, q = [], False
    for c in line:
        if c == '"':
            q = not q
            continue
        if q:
            continue
        if c == "'":
            break
        out.append(c)
    s = "".join(out)
    if re.match(r'^\s*REM\b', s, re.I):
        return ""
    return s


def sources():
    for d, dirs, files in os.walk(ROOT):
        rel = os.path.relpath(d, ROOT)
        top = rel.split(os.sep)[0]
        if top in SKIP_DIRS:
            dirs[:] = []
            continue
        dirs.sort()
        for f in sorted(files):
            if f.upper().endswith((".BM", ".BAS")):
                p = os.path.join(d, f)
                r = os.path.relpath(p, ROOT).replace(os.sep, "/")
                if r not in SKIP_FILES:
                    yield p


def generate():
    fk = field_keys()
    uses = {}  # routine (upper) -> [keys]
    for p in sources():
        cur = None
        for raw in open(p, encoding="utf-8", errors="replace"):
            s = code_part(raw.rstrip("\n"))
            if cur is None:
                m = START_RE.match(s)
                if m:
                    cur = m.group(1).upper()
                    uses.setdefault(cur, [])
                continue
            if END_RE.match(s):
                cur = None
                continue
            for m in REF_RE.finditer(s):
                k = fk.get(m.group(1).upper())
                if k and k not in uses[cur]:
                    uses[cur].append(k)
    rows = sorted((r, ks) for r, ks in uses.items() if ks)
    head = [
        "''",
        "' DRAW - CFG/THEME-USES.BM",
        "' =============================================================================",
        "' GENERATED by DEV/theme-uses-gen.py (make runs it). DO NOT EDIT.",
        "'",
        "' The theme keys each SUB / FUNCTION reads (THEME.<field>, mapped to its key by",
        "' THEME_apply_kv%), in the order it first reads them. Theme Edit's COMPUTED",
        "' properties: a part drawn by routine R lists THEMEU_keys$(\"R\").",
        "' %d routines." % len(rows),
        "'",
        "$INCLUDEONCE",
        "",
        "''",
        "' \"KEY KEY ...\" read by routine rtn (any case, no type suffix); \"\" = none / unknown.",
        "'",
        "FUNCTION THEMEU_keys$ (rtn AS STRING)",
        "    SELECT CASE UCASE$(rtn)",
    ]
    body = []
    for r, ks in rows:
        txt = " ".join(ks)
        # keep lines short: long lists are built in pieces
        parts = []
        while txt:
            if len(txt) <= 200:
                parts.append(txt)
                break
            cut = txt.rfind(" ", 0, 200)
            parts.append(txt[:cut])
            txt = txt[cut + 1:]
        expr = ' + " " + '.join('"%s"' % x for x in parts)
        body.append('        CASE "%s": THEMEU_keys$ = %s' % (r, expr))
    tail = [
        "    END SELECT",
        "END FUNCTION",
        "",
    ]
    return "\n".join(head + body + tail), len(rows)


def main():
    text, n = generate()
    cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in sys.argv:
        if cur != text:
            print("theme-uses-gen: CFG/THEME-USES.BM is out of date - run python3 DEV/theme-uses-gen.py")
            sys.exit(1)
        print("theme-uses-gen: up to date (%d routines)" % n)
        return
    if cur != text:
        open(OUT, "w", encoding="utf-8").write(text)
        print("theme-uses-gen: wrote CFG/THEME-USES.BM (%d routines)" % n)


if __name__ == "__main__":
    main()
